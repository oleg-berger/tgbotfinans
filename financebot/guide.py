def welcome_screen(token):
    return Screen(WELCOME, [[("📖 Пройти гайд по боту", f"d:{token}:guide")]])


def guide_screen(page, token):
    title, body = GUIDE_PAGES[page]
    nav = [("← Назад", f"d:{token}:back")]
    if page < len(GUIDE_PAGES) - 1:
        nav.append(("Далее →", f"d:{token}:next"))
    rows = [nav]
    if page == len(GUIDE_PAGES) - 1:
        rows.append([("🗂 Создать категории", f"d:{token}:categories")])
    return Screen(f"<b>{page + 1}/{len(GUIDE_PAGES)} · {title}</b>\n\n{body}", rows,
                  photo=f"assets/guide/page-{page + 1:02d}.png")
